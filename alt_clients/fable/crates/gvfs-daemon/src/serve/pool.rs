//! Request arenas: all the memory a `POST /gvfs/objects` / `POST /gvfs/sizes` / loose
//! object request may use, pre-allocated at boot and leased through a semaphore (built-in
//! backpressure: at most `--arenas` such requests are in flight).

use std::sync::{Arc, Mutex};

use tokio::sync::{OwnedSemaphorePermit, Semaphore};

use crate::arena::Arena;
use crate::frames::FrameRing;
pub use crate::frames::{FRAME_BUF_BYTES, promoted};
use crate::zlib::{Deflater, Inflater};

/// One planned pack entry: `slab` is the catalog probe index.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct PlanEntry {
    pub slab: u8,
    /// Resolve and deflate while streaming (a delta whose base is not in the pack).
    pub convert: bool,
    pub offset: u64,
    pub len: u32,
    pub slot: u32,
    /// Plan index of the OFS_DELTA base when the entry stays a delta (u32::MAX = none).
    pub base: u32,
}

#[derive(Debug)]
pub struct RequestArena {
    /// Request body, inflated objects, generated bytes.
    pub bytes: Arena,
    pub plan: Vec<PlanEntry>,
    /// Walk stack of `(slab, slot, commit depth)`; depth 0 marks a tree item.
    pub stack: Vec<(u8, u32, u32)>,
    /// Per-entry numbers: pack positions (`objects`) or sizes (`sizes`).
    pub nums: Vec<u64>,
    /// Delta chain offsets during resolution.
    pub chain: Vec<u64>,
    pub inflater: Option<Inflater>,
    pub deflater: Option<Deflater>,
    /// Staging for generated response frames (see [`crate::frames`]).
    pub frames: FrameRing,
    /// Seen bits over every probe slab's mphf slots (`seen_base[k]` is slab k's first bit).
    pub seen: Vec<u64>,
    pub seen_base: [u64; 64],
}

impl RequestArena {
    pub fn new(bytes: usize, max_entries: usize, seen_bits: u64) -> Self {
        let words = usize::try_from(seen_bits.saturating_add(63) / 64).unwrap_or(0);
        Self {
            bytes: Arena::new(bytes),
            plan: Vec::with_capacity(max_entries),
            stack: Vec::with_capacity(max_entries),
            nums: Vec::with_capacity(max_entries),
            chain: Vec::with_capacity(4096),
            inflater: Some(Inflater::new()),
            deflater: Some(Deflater::new(6)),
            frames: FrameRing::new(),
            seen: vec![0u64; words],
            seen_base: [0u64; 64],
        }
    }

    pub fn reset(&mut self) {
        self.bytes.reset();
        self.plan.clear();
        self.stack.clear();
        self.nums.clear();
        self.frames.reset();
        // Only the words touched by a request are dirty, but clearing all of them is a
        // sequential memset over ≤ a few MiB; cheap next to the request itself.
        self.seen.fill(0);
    }

    /// Back to the state right after the request body was read (`keep` bytes of the arena),
    /// for a second pass over the same request against a newer catalog.
    pub fn reset_keep(&mut self, keep: usize) {
        self.bytes.truncate(keep);
        self.plan.clear();
        self.stack.clear();
        self.nums.clear();
        self.seen.fill(0);
    }

    /// Lays out the seen-bitset for slabs of the given key counts; grows the bitset if a
    /// new manifest needs more (only right after a manifest change, never steady state).
    pub fn layout_seen(&mut self, key_counts: impl Iterator<Item = u64>) {
        let mut acc = 0u64;
        for (k, n) in key_counts.enumerate() {
            if let Some(b) = self.seen_base.get_mut(k) {
                *b = acc;
            }
            acc = acc.saturating_add(n);
        }
        let words = usize::try_from(acc.saturating_add(63) / 64).unwrap_or(0);
        if self.seen.len() < words {
            self.seen.resize(words, 0);
        }
    }

    /// Marks `(slab, slot)`; returns true if it was not seen before.
    #[inline]
    pub fn mark(&mut self, slab: usize, slot: u32) -> bool {
        let bit = self
            .seen_base
            .get(slab)
            .copied()
            .unwrap_or(0)
            .saturating_add(u64::from(slot));
        let Some(w) = self.seen.get_mut((bit / 64) as usize) else {
            return true;
        };
        let m = 1u64 << (bit % 64);
        if *w & m != 0 {
            return false;
        }
        *w |= m;
        true
    }
}

#[derive(Debug)]
pub struct ArenaPool {
    sem: Arc<Semaphore>,
    // Arenas stay boxed so a lease hands out the box instead of moving the ~1 KiB struct.
    #[allow(clippy::vec_box)]
    free: Mutex<Vec<Box<RequestArena>>>,
}

impl ArenaPool {
    pub fn new(count: usize, bytes: usize, max_entries: usize, seen_bits: u64) -> Arc<Self> {
        let arenas = (0..count)
            .map(|_| Box::new(RequestArena::new(bytes, max_entries, seen_bits)))
            .collect();
        Arc::new(Self {
            sem: Arc::new(Semaphore::new(count)),
            free: Mutex::new(arenas),
        })
    }

    /// Waits for a free arena (cancel-safe).
    pub async fn lease(self: &Arc<Self>) -> Option<ArenaGuard> {
        let permit = Arc::clone(&self.sem).acquire_owned().await.ok()?;
        let arena = self.free.lock().ok()?.pop()?;
        Some(ArenaGuard {
            arena: Some(arena),
            pool: Arc::clone(self),
            _permit: permit,
        })
    }
}

/// A leased arena; returns itself (reset) to the pool on drop.
#[derive(Debug)]
pub struct ArenaGuard {
    arena: Option<Box<RequestArena>>,
    pool: Arc<ArenaPool>,
    _permit: OwnedSemaphorePermit,
}

impl ArenaGuard {
    #[inline]
    pub fn get(&mut self) -> &mut RequestArena {
        // The option is only emptied in `drop`.
        self.arena
            .get_or_insert_with(|| Box::new(RequestArena::new(0, 0, 0)))
    }
}

impl Drop for ArenaGuard {
    fn drop(&mut self) {
        if let Some(mut a) = self.arena.take() {
            a.reset();
            if let Ok(mut free) = self.pool.free.lock() {
                free.push(a);
            }
        }
    }
}
